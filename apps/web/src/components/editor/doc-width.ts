/**
 * 正文框宽度的上下限。
 *
 * 只在桌面端用（Ctrl + 鼠标拖两侧边框），手机端不接这条逻辑 —— 手机上拖动、命中判定、
 * 屏幕宽度都是另一套，搬过来必出 bug，等专门做移动端时再单独设计。
 *
 * 下限是**写死的像素**：30 个汉字一行，按默认字号 16px 算 = 480px 正文宽。
 *
 * 这条下限要穿过两层内边距才落到正文上，而被拖的是**整列**（标题、工具栏、正文框
 * 一起变窄，四层边界始终对齐，见 NoteEditView 的 .body），所以两层都算进去：
 *   480（正文）+ 32×2（正文框自己的 --surface-pad-x）+ 32×2（列外层的 --body-pad-x）= 608
 * 这一档下用户看到的正文框正好 544px、正文正好 480px —— 与「框宽下限 544」是一回事，
 * 只是一个量在列上、一个量在框上。
 *
 * 不跟着字号换算 —— 字号调到 18px 时这一档就是 27 字一行，这是写死像素的必然结果。
 *
 * 上限**不是一个数，而是当前的可用宽**（内容区满宽）：窗口越大能拉得越宽，
 * 窗口一小可调范围就跟着收窄；内容区本身不到下限时范围塌成一点，等于只能填满。
 */
/** 一行的正文宽：30 个汉字 × 默认字号 16px */
const LINE_PX = 30 * 16;
/** 正文框自己的左右内边距（--sp-4），框宽 = 正文宽 + 两侧 */
const BOX_PAD_PX = 32;
/** 正文列的外层左右内边距（--sp-4），被拖的正是这一层 */
const COLUMN_PAD_PX = 32;

export const DOC_WIDTH_MIN = LINE_PX + (BOX_PAD_PX + COLUMN_PAD_PX) * 2;

/**
 * 夹到 [下限, 可用宽]。
 *
 * 可用宽自己不够下限时（窗口很窄），上下限就重合在可用宽上 —— 用 Math.min 取一次下限，
 * 免得出现「下限 > 上限」这种要靠调用方再判一次的中间态。
 */
export function clampDocWidth(px: number, available: number): number {
  return Math.min(available, Math.max(Math.min(DOC_WIDTH_MIN, available), px));
}
